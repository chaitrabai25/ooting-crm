/**
 * Reverse lookup index for direct English phrase matching
 */
const lookupMaps: Record<Language, Map<string, string>> = {
  en: new Map(),
  kn: new Map(),
  hi: new Map(),
};

// Build case-insensitive lookup maps
Object.keys(DICTIONARY.en).forEach((key) => {
  const enVal = DICTIONARY.en[key].toLowerCase().trim();
  lookupMaps.en.set(enVal, DICTIONARY.en[key]);
  lookupMaps.kn.set(enVal, DICTIONARY.kn[key] || DICTIONARY.en[key]);
  lookupMaps.hi.set(enVal, DICTIONARY.hi[key] || DICTIONARY.en[key]);

  // Also index by key directly
  lookupMaps.en.set(key.toLowerCase(), DICTIONARY.en[key]);
  lookupMaps.kn.set(key.toLowerCase(), DICTIONARY.kn[key] || DICTIONARY.en[key]);
  lookupMaps.hi.set(key.toLowerCase(), DICTIONARY.hi[key] || DICTIONARY.en[key]);
});

/**
 * Look up translation for a key or English text
 */
export function translateKey(keyOrText: string, lang: Language): string | null {
  if (lang === 'en') return null;
  const normalized = keyOrText.trim().toLowerCase();
  const direct = lookupMaps[lang].get(normalized);
  if (direct) return direct;
  return null;
}
