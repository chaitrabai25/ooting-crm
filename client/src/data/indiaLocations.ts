/**
 * Helper to check if a country represents India (default)
 */
export function isIndia(country?: string | null): boolean {
  if (!country) return true;
  const c = country.trim().toLowerCase();
  return c === '' || c === 'india' || c === 'in' || c === 'ind';
}

/**
 * Get sorted list of districts for a given Indian State name
 */
export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  const found = INDIA_STATES_AND_DISTRICTS.find(
    (s) => s.state.toLowerCase() === stateName.trim().toLowerCase()
  );
  return found ? found.districts : [];
}
