// Helper to calculate column widths based on contents
function computeColWidths(data, headers) {
  const colWidths = headers.map(h => ({ wch: h.length + 3 }));
  data.forEach(row => {
    headers.forEach((h, idx) => {
      const val = row[h] ? String(row[h]) : '';
      // Limit check to avoid overly massive column sizes
      const len = Math.min(Math.max(val.length, colWidths[idx].wch), 60);
      colWidths[idx].wch = len;
    });
  });
  return colWidths;
}

